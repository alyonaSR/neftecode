def godt_t90(m: Mapping) -> float:
    T12, F15, W7, T23, F1, F26 = (m["242000:T12"], m["242000:F15"], m["242000:W7"],
                                   m["242000:T23"], m["242000:F1"], m["242000:F26"])
    return 162.998 + 0.12945 * T12 + 59.57 * (F15 / 2000) + 0.00036 * W7 + 0.26366 * T23 - 424.72638 * F1 / F26


def godt_t50(m: Mapping) -> float:
    P13, F9, T6 = m["242000:P13"], m["242000:F9"], m["242000:T6"]
    return 44.625 + 10.0224 * P13 + 0.06981 * F9 + 0.471 * T6


def godt_i250(m: Mapping) -> float:
    T5, T11, F25, F14, T23, T16 = (m["242000:T5"], m["242000:T11"], m["242000:F25"],
                                    m["242000:F14"], m["242000:T23"], m["242000:T16"])
    return 84.585 - 0.21172 * T5 + 0.12137 * T11 - 0.00014 * F25 + 0.56248 * F14 - 0.16317 * T23 + 0.20272 * T16


def godt_cloud(m: Mapping) -> float:
    F22, W7, F25, F1, T6, F9, T16 = (m["242000:F22"], m["242000:W7"], m["242000:F25"],
                                      m["242000:F1"], m["242000:T6"], m["242000:F9"], m["242000:T16"])
    return (0.0002 * F22 + 0.0021 * W7 + 0.00008 * F25 - 0.30656 * F1
            + 0.12018 * T6 + 0.01916 * F9 - 48.254 - 0.05249 * T16 + 0.00011)


def godt_cfpp(m: Mapping) -> float:
    T23, P8, F9, W7, P24 = m["242000:T23"], m["242000:P8"], m["242000:F9"], m["242000:W7"], m["242000:P24"]
    return 0.22088 * T23 - 102.375 - 47.75834 * P8 + 0.03862 * F9 + 43.60207 * W7 + 43.81849 * P24


def godt_ibp(m: Mapping) -> float:
    F26, F22, P13, P24, F14, W4, T23, T16 = (
        m["242000:F26"], m["242000:F22"], m["242000:P13"], m["242000:P24"],
        m["242000:F14"], m["242000:W4"], m["242000:T23"], m["242000:T16"])
    return (137.762 - 0.0653 * F26 + 0.00011 * F22 + 5.78137 * P13 - 34.58028 * P24
            - 0.00993 * F14 - 0.99962 * W4 + 0.32232 * T23 - 0.09406 * T16)


