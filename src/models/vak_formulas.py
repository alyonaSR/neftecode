def avt_350_t50(m: Mapping) -> float:
    """
    ЗАМЕНЕНА ЦЕЛИКОМ (формулы_ВАК.xlsx, 2026-09-17): у нас была другая
    формула (4 члена, константа 981.06539). Организаторы прислали
    другую -- 7 членов, константа 493.6798, добавлены T66/T33. Это не
    патч коэффициента, это другая модель. Проверено на контрольном
    примере: T42=275.79, T48=355.21, F31=498.33, F57=20.53, T66=256.08,
    T33=336.20 -> 299.67.
    """
    T42, T48, F31, F57, T66, T33 = (m["AVT:T42"], m["AVT:T48"], m["AVT:F31"],
                                     m["AVT:F57"], m["AVT:T66"], m["AVT:T33"])
    return (493.6798 + 1.281193 * T42 - 0.955342 * T48 - 0.018454 * F31
            + 0.265904 * F57 - 0.082047 * T66 - 0.545083 * T33)


def avt_350_i350(m: Mapping) -> float:
    """
    По файлу формулы_ВАК.xlsx (2026-09-17): знак при T6 был минус,
    должен быть плюс. Проверено на контрольном примере: L43=60.08,
    T6=234.73, T18=158.40, F64=104.56, T15=135.58, T11=56.14 -> 88.82.
    """
    L43, T6, T18, F64, T15, T11 = (m["AVT:L43"], m["AVT:T6"], m["AVT:T18"],
                                    m["AVT:F64"], m["AVT:T15"], m["AVT:T11"])
    return 39.562 - 1.62865 * L43 + 0.76664 * T6 - 0.22361 * T18 + 0.00031 * F64 * (T15 - T11)


def avt_350_d15(m: Mapping) -> float:
    T42, T48, F31, F57 = m["AVT:T42"], m["AVT:T48"], m["AVT:F31"], m["AVT:F57"]
    return 983.092 + 0.27467 * T42 - 0.49014 * T48 - 0.32983 * (F31 / F57)


def avt_350_cfpp(m: Mapping) -> float:
    T48, T40, F31, F57 = m["AVT:T48"], m["AVT:T40"], m["AVT:F31"], m["AVT:F57"]
    return 19.27111 - 0.10582 * T48 + 0.13836 * T40 - 0.42304 * (F31 / F57)


