"""
Формулы виртуальных анализаторов (ВАК) с листа "ВАК" Теги_хакатон.xlsx.

Чистые функции: тег-словарь -> число. Никакого ML, никакого Interval,
никакого знания про ProcessState. Единый источник правды, чтобы формулу
не копировать в трёх местах (models/, аудит, тесты).

Работает и с dict (одна строка), и с pd.DataFrame (векторизованно
по колонкам вида 'AVT:F30') - доступ везде через m["..."].

СТАТУС ПОСЛЕ АУДИТА (сверка с ЛИМС + правки организаторов
на Q&A от 15.09) И ПОСЛЕ СВЕРКИ С "формулы_ВАК.xlsx" (новый файл от
организаторов, получен 2026-09-17, содержит контрольные примеры расчёта
для каждой формулы -- каждая функция ниже проверена арифметически против
этих примеров, не только по коэффициентам):

  НАЙДЕНЫ И ИСПРАВЛЕНЫ РЕАЛЬНЫЕ БАГИ в нашем коде (не в формулах
  организаторов -- у нас был неверный перенос):
    avt_240_350_d15  -- числитель дроби был F30, должен быть F65.
                        Разные теги, не опечатка в имени.
    avt_240_350_cfpp -- скобки стояли не там: было
                        0.47309*(F65/F32 + F30), должно быть
                        0.47309*(F65/(F32+F30)). Это и объясняло
                        "corr -0.32, знак противоположен физике" --
                        формула не была сломана, была неверно
                        транскрибирована. Больше НЕ formula_fn=None,
                        используется как baseline для feed_cfpp_c.
    avt_350_i350     -- знак при T6 был минус, должен быть плюс.
    avt_350_t50      -- у нас была старая/другая формула (4 члена,
                        константа 981.06539). Организаторы прислали
                        другую (7 членов, константа 493.6798) -- заменена
                        целиком, не патч коэффициента.

  РАБОЧИЕ, используются как baseline в FormulaPlusResidual:
    avt_240_350_ebp, avt_240_350_d15 (после фикса), avt_240_350_cfpp
    (после фикса), avt_350_d15, avt_350_cfpp, avt_350_t50 (после фикса)

  ИСПРАВЛЕНЫ организаторами (координаты см. ниже), масштаб адекватен,
  но используются в GOModel, не здесь:
    godt_t90, godt_t50, godt_cloud, godt_cfpp -- сверены с новым файлом
    построчно, расхождений с нашим кодом не найдено, менять нечего.

  НЕ РЕАЛИЗОВАНЫ намеренно: godt_d15, godt_t95 -- формулы содержат член
  LIMS:24-2000.Pipeline.*/LIMS.95%.T, что при прямой подстановке --
  утечка из будущего. Подтверждено и в новом файле формул (термин
  LIMS.D15 / LIMS.95%.T виден в исходнике). Не в контракте
  GOModel.outputs, отложено осознанно, не забыто.

  Флаги достоверности входных тегов см. config/tags.yaml. Часть кодов
  (T66, F36, T37, T40, T58, T42, F31, F57, L43, F64, T15, T11) не входит
  в изначально верифицированные 13 тегов, но подтверждена позиционно по
  рукописной P&ID-схеме АВТ (Нефтекод_2.0/АВТ_схемы.pdf + doc0062832..4632).

  ВАЖНО ДЛЯ КОМАНДЫ: новый файл "теги АВТ_24-2000.xlsx"
  даёт официальные описания вместо наших догадок. Три спорных тега
  242000:T6/T11/T18 подтверждены РОВНО как мы и предполагали по данным
  (T6, T11 -- температуры, не сера/расход; T18 -- буквально ВАК вспышки
  ГОДТ). Но 242000:F26 оказался НЕ расходом сырья на установку, а
  расходом ГИДРООЧИЩЕННОГО ДТ на выходе (в цех №8) -- реальный расход
  сырья это F9 (массовый) или F15 (объёмный). agents/reliability.py
  сейчас использует F26 как "load" (нагрузка по сырью) -- семантически
  неверно, хотя численно может вести себя похоже. Не трогаю чужой файл,
  но стоит поправить.
"""
from __future__ import annotations

from typing import Callable, Dict, List, Mapping, Tuple

Formula = Callable[[Mapping], float]


# ---------------------------------------------------------------------
# АВТ, фракция 240-350
# ---------------------------------------------------------------------

def avt_240_350_d15(m: Mapping) -> float:
    """
    По файлу формулы_ВАК.xlsx (2026-09-17): числитель дроби -- F65,
    у нас был F30 (неверный перенос, не опечатка в имени тега).
    Проверено на контрольном примере организаторов: F65=789.54,
    F32=79.00, F30=98.97, T66=255.04, T33=335.41 -> 849.83.
    """
    F30, F32, F65, T66, T33 = (m["AVT:F30"], m["AVT:F32"], m["AVT:F65"],
                                m["AVT:T66"], m["AVT:T33"])
    return 791.22872 - 5.30294 * (F65 / (F32 + F30)) + 0.52755 * T66 - 0.15629 * T33


def avt_240_350_t50(m: Mapping) -> float:
    F7, F30, F34, F45, F59, F63 = (m["AVT:F7"], m["AVT:F30"], m["AVT:F34"],
                                    m["AVT:F45"], m["AVT:F59"], m["AVT:F63"])
    return (283.177 - 0.01685 * F7 + 0.06248 * F30 + 0.22048 * F34
            - 0.25816 * F45 - 0.12159 * F59 + 0.01221 * F63)


def avt_240_350_ebp(m: Mapping) -> float:
    F30, T33, F36, T37, T40, T58 = (m["AVT:F30"], m["AVT:T33"], m["AVT:F36"],
                                     m["AVT:T37"], m["AVT:T40"], m["AVT:T58"])
    return (813.883 + 2.66463 * F30 - 0.20239 * T33 - 3.65888 * F36
            - 14.08235 * T37 - 1.32603 * T40 + 14.60206 * T58)


def avt_240_350_cfpp(m: Mapping) -> float:
    """
    По файлу формулы_ВАК.xlsx (2026-09-17): скобки стояли не там.
    Было 0.47309*(F65/F32 + F30) -- по приоритету операций это
    (F65/F32) + F30, огромный лишний член. Должно быть
    0.47309*(F65/(F32+F30)). Формула НЕ была физически сломана --
    была неверно транскрибирована. Проверено на контрольном примере:
    T33=335.41, P67=1.10, P4=3.85, F65/(F32+F30)=4.4365 -> -5.53.
    """
    T33, P67, P4, F65, F32, F30 = (m["AVT:T33"], m["AVT:P67"], m["AVT:P4"],
                                    m["AVT:F65"], m["AVT:F32"], m["AVT:F30"])
    return 31.40363 - 0.06784 * T33 + 17.411 * P67 - 8.11544 * P4 - 0.47309 * (F65 / (F32 + F30))


